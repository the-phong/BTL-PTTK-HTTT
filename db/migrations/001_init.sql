CREATE TABLE IF NOT EXISTS tblThanhVien (
  MaTV BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  HoTen VARCHAR(120) NOT NULL,
  NgaySinh DATE NOT NULL,
  SoDienThoai VARCHAR(20) NOT NULL UNIQUE,
  Email VARCHAR(190) NOT NULL UNIQUE,
  DiaChi VARCHAR(255) NOT NULL,
  MatKhau VARCHAR(255) NOT NULL,
  NgayTao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tblKhachHang (
  MaKH BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaTV BIGINT UNSIGNED NOT NULL UNIQUE,
  MaKhachHang VARCHAR(24) NOT NULL UNIQUE,
  FOREIGN KEY (MaTV) REFERENCES tblThanhVien(MaTV) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tblXeOTo (
  MaXe BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaXeHienThi VARCHAR(24) NOT NULL UNIQUE,
  TenXe VARCHAR(120) NOT NULL,
  BienSo VARCHAR(24) NOT NULL UNIQUE,
  LoaiXe VARCHAR(40) NOT NULL,
  SoCho TINYINT UNSIGNED NOT NULL,
  HangXe VARCHAR(60) NOT NULL,
  NamSanXuat SMALLINT UNSIGNED NOT NULL,
  MoTa TEXT,
  Anh VARCHAR(255),
  DonGiaGio DECIMAL(12,2) NOT NULL,
  TrangThai ENUM('SAN_SANG','BAO_TRI','NGUNG_CHO_THUE') NOT NULL DEFAULT 'SAN_SANG',
  INDEX idx_xe_loc(LoaiXe, SoCho, TrangThai),
  CHECK (SoCho > 0), CHECK (DonGiaGio >= 0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tblPhieuDatXe (
  MaPhieu BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaPhieuHienThi VARCHAR(32) NOT NULL UNIQUE,
  MaKH BIGINT UNSIGNED NOT NULL,
  ThoiGianDat TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  TrangThai ENUM('CHO_XAC_NHAN','DA_XAC_NHAN','DA_HUY','HOAN_TAT') NOT NULL DEFAULT 'DA_XAC_NHAN',
  TongTien DECIMAL(14,2) NOT NULL DEFAULT 0,
  FOREIGN KEY (MaKH) REFERENCES tblKhachHang(MaKH) ON DELETE RESTRICT,
  INDEX idx_phieu_kh(MaKH, ThoiGianDat)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tblChiTietPhieuDat (
  MaChiTiet BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MaPhieu BIGINT UNSIGNED NOT NULL,
  MaXe BIGINT UNSIGNED NOT NULL,
  ThoiGianNhan DATETIME NOT NULL,
  ThoiGianTra DATETIME NOT NULL,
  DonGiaGio DECIMAL(12,2) NOT NULL,
  SoGio DECIMAL(10,2) NOT NULL,
  ThanhTien DECIMAL(14,2) NOT NULL,
  FOREIGN KEY (MaPhieu) REFERENCES tblPhieuDatXe(MaPhieu) ON DELETE CASCADE,
  FOREIGN KEY (MaXe) REFERENCES tblXeOTo(MaXe) ON DELETE RESTRICT,
  INDEX idx_ct_xe_thoi_gian(MaXe, ThoiGianNhan, ThoiGianTra),
  CHECK (ThoiGianTra > ThoiGianNhan), CHECK (DonGiaGio >= 0), CHECK (SoGio > 0)
) ENGINE=InnoDB;
